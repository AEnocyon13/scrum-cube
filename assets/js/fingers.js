/*
 * fingers.js — 手ごとの標準的な指使い（フィンガートリック）の一例
 * 持ち方は「両手の親指が前面、人差し指が上面の後ろ」の基本グリップを想定。
 */
(function (global) {
  'use strict';
  // [短い表記, 説明]
  const TABLE = {
    R: ['右手首', '右手首を返して上へ'],
    "R'": ['右手首', '右手首を手前に返して下へ'],
    R2: ['右手首×2', '右手首で2回（または上→上）'],
    L: ['左手首', '左手首を手前に返して下へ'],
    "L'": ['左手首', '左手首を返して上へ'],
    L2: ['左手首×2', '左手首で2回'],
    U: ['右人差', '右人差し指で上面を弾く'],
    "U'": ['左人差', '左人差し指で上面を弾く'],
    U2: ['右人差中', '右人差し指→中指の順に2回弾く（ダブルフリック）'],
    "U2'": ['左人差中', '左人差し指→中指で2回弾く'],
    D: ['左薬指', '左薬指で下面を引く'],
    "D'": ['右薬指', '右薬指で下面を引く'],
    D2: ['薬指×2', '左右どちらかの薬指で2回'],
    F: ['右人差/左親', '右人差し指で前面を押す（または左親指）'],
    "F'": ['右親/左人差', '右親指で前面を押す（または左人差し指）'],
    F2: ['×2', '前面を2回（持ち替えるか、右人差し指で2回）'],
    B: ['持ち替え', '後面は右薬指で弾くか、持ち替えて回す'],
    "B'": ['持ち替え', '後面は左薬指で弾くか、持ち替えて回す'],
    B2: ['持ち替え', '持ち替えて回すことが多い'],
    M: ['左薬指', '左薬指でM列を引く'],
    "M'": ['薬指', '薬指でM列を下面側から押し上げる'],
    M2: ['薬指×2', '薬指で2回弾く（M2は左右交互でも可）'],
    r: ['右手首', '右手首で2層ごと上へ'],
    "r'": ['右手首', '右手首で2層ごと下へ'],
    f: ['右人差', '前2層を右人差し指で押す'],
    "f'": ['右親', '前2層を右親指で押す'],
  };
  function entry(m) {
    const k = m.label;
    if (TABLE[k]) return TABLE[k];
    if (/^[xyz]/.test(k)) return ['持ち替え', 'キューブ全体を持ち替える'];
    if (/^[ES]/.test(k)) return ['持ち替え', '中層は持ち替えて回すか、薬指で弾く'];
    const base = TABLE[k.replace(/2$/, '')];
    return base ? [base[0] + '×2', base[1] + '（2回）'] : ['—', '持ち替えて回す'];
  }
  global.Fingers = {
    short: (m) => entry(m)[0],
    of: (m) => entry(m)[1],
  };
})(window);
